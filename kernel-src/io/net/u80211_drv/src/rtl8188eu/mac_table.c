int u80211_drv_rtl8188eu_mac_load_table(u80211_drv_device_handle_t device) {
	for (size_t i = 0; i < ARRAY_SIZE(rtl8188eu_mac_table); ++i) {
		int status = u80211_drv_rtl8188eu_reg_write8(device, rtl8188eu_mac_table[i].reg, rtl8188eu_mac_table[i].value);
		if (status != U80211_DRV_STATUS_SUCCESS) {
			u80211_drv_kernel_print(U80211_DRV_KERNEL_PRINT_LEVEL_ERROR, "rtl8188eu: MAC table write failed");
			return status;
		}
	}

	return u80211_drv_rtl8188eu_reg_write8(device, U80211_DRV_RTL8188EU_REG_MAX_AGGR_NUM, U80211_DRV_RTL8188EU_REG_MAX_AGGR_NUM_8188EU);
}
